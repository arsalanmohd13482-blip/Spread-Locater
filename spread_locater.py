"""*   **Task 7: Probability Density (PDF) & Cumulative Distribution (CDF) Functions**  
    Plot the empirical PDF and CDF curves for the transaction amounts, and interpret how cumulative boundaries align with customer purchasing behavior.

"""

import matplotlib.pyplot as plt

# Select valid transaction amounts
amount = df["transaction_amount"].dropna()
amount = amount[amount > 0].sort_values()

# ---------------- PDF ----------------
# Histogram-based empirical density
pdf_values, bin_edges = np.histogram(
    amount,
    bins=30,
    density=True
)

bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2

# ---------------- CDF ----------------
# Empirical cumulative probability
cdf_values = np.arange(1, len(amount) + 1) / len(amount)

# ---------------- Plot PDF ----------------
plt.figure(figsize=(8, 5))
plt.plot(bin_centers, pdf_values)
plt.xlabel("Transaction Amount (₹)")
plt.ylabel("Probability Density")
plt.title("Empirical PDF of Transaction Amounts")
plt.grid()
plt.show()

# ---------------- Plot CDF ----------------
plt.figure(figsize=(8, 5))
plt.plot(amount, cdf_values)
plt.xlabel("Transaction Amount (₹)")
plt.ylabel("Cumulative Probability")
plt.title("Empirical CDF of Transaction Amounts")
plt.grid()
plt.show()

# ---------------- Selected CDF boundaries ----------------
boundaries = [1000, 2000, 3000, 5000, 10000]

print("Cumulative probabilities:")

for value in boundaries:
    probability = (amount <= value).mean()
