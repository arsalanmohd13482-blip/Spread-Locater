std_amount = amount.std()

# Calculate individual Z-scores
z_scores = (amount - mean_amount) / std_amount

# Add Z-scores to dataframe
df.loc[amount.index, "z_score"] = z_scores

# Z-score for ₹5,000
x = 5000
z_5000 = (x - mean_amount) / std_amount

# Probability of transaction exceeding ₹5,000
probability = 1 - norm.cdf(z_5000)

print("Mean transaction amount:", mean_amount)
print("\nStandard deviation:", std_amount)
print("\nThe Z-Score for the Raw Transaction Amount:""\n",z_scores)
print("\nZ-score for ₹5,000:", z_5000)
print("\nProbability of transaction > ₹5,000:", probability)
