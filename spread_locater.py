"""*   **Task 6: Z-Score Calculation & Probability Extraction**  
    Compute individual Z-scores for raw transaction amounts to standardize the data. Utilize these Z-scores to calculate the formal probability of a single customer transaction exceeding ₹5,000.


"""

from scipy.stats import norm

